CREATE TABLE project_participation (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(255) NOT NULL REFERENCES project_definition(project_id) ON UPDATE CASCADE ON DELETE CASCADE,
    user_id VARCHAR(255) NOT NULL REFERENCES user_attrs(user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    backfill_status VARCHAR(32) NOT NULL DEFAULT 'NOT_REQUESTED'
        CHECK (backfill_status IN ('NOT_REQUESTED', 'NOT_NEEDED', 'PENDING', 'COMPLETED')),
    created TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    updated TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    UNIQUE (project_id, user_id)
);
